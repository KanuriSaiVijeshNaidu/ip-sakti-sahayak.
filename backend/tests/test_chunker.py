# ??? chunk_file ???????????????????????????????????????????????????????????????

def test_chunk_file_returns_list(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    assert isinstance(chunks, list)
    assert len(chunks) > 0


def test_chunk_file_all_chunks_have_text(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    for c in chunks:
        assert c.text.strip(), f"Chunk {c.chunk_index} has empty text"


def test_chunk_file_respects_token_limit(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    for c in chunks:
        assert c.token_count <= MAX_TOKENS + 20, (
            f"Chunk {c.chunk_index} has {c.token_count} tokens (limit={MAX_TOKENS})"
        )


def test_chunk_file_extracts_domain(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    for c in chunks:
        assert c.domain == "patents", f"Expected domain=patents, got {c.domain}"


def test_chunk_file_extracts_jurisdiction(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    for c in chunks:
        assert c.jurisdiction == "IN", f"Expected jurisdiction=IN, got {c.jurisdiction}"


def test_chunk_file_extracts_corpus_version(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    for c in chunks:
        assert c.corpus_version == "v1"


def test_chunk_file_sequential_indices(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    for i, c in enumerate(chunks):
        assert c.chunk_index == i, f"Expected chunk_index={i}, got {c.chunk_index}"


def test_chunk_file_unique_ids(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file)
    ids = [c.id for c in chunks]
    assert len(ids) == len(set(ids)), "Chunk IDs are not unique"


def test_chunk_file_override_meta(sample_txt_file: Path):
    chunks = chunk_file(sample_txt_file, override_meta={"domain": "fssai", "jurisdiction": "GLOBAL"})
    for c in chunks:
        assert c.domain == "fssai"
        assert c.jurisdiction == "GLOBAL"


def test_chunk_to_dict(sample_txt_file: Path):
    chunk = chunk_file(sample_txt_file)[0]
    d = chunk.to_dict()
    required_keys = {"id", "text", "section_title", "chunk_index", "token_count",
                     "source_title", "domain", "jurisdiction", "corpus_version"}
    assert required_keys.issubset(d.keys())


