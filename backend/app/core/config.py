"""
backend/app/core/config.py
??????????????????????????
Centralised settings loaded from environment variables / .env file.
All other modules import `settings` from here; never read os.environ directly.
"""
from __future__ import annotations

import json
from functools import lru_cache
from typing import List, Literal

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=False,
        extra="ignore",
    )

    # ?? Application ?????????????????????????????????????????????????????????
    app_name: str = "IP-SAKTI Sahayak"
    app_version: str = "0.1.0"
    app_env: Literal["development", "staging", "production"] = "development"
    debug: bool = True

    # ?? API ??????????????????????????????????????????????????????????????????
    api_host: str = "0.0.0.0"
    api_port: int = 8000
    api_prefix: str = "/api"
    allowed_origins: List[str] = Field(
        default=["http://localhost:3000", "http://localhost:3001"]
    )

    @field_validator("allowed_origins", mode="before")
    @classmethod
    def parse_origins(cls, v: object) -> List[str]:
        if isinstance(v, str):
            try:
                return json.loads(v)
            except json.JSONDecodeError:
                return [v]
        return v  # type: ignore[return-value]

    # ?? Database ?????????????????????????????????????????????????????????????
    database_url: str = (
        "postgresql+asyncpg://ipsakti_user:ipsakti_secret@localhost:5432/ipsakti"
    )

    # ?? Embedding ????????????????????????????????????????????????????????????
    embed_model: str = "BAAI/bge-m3"
    embed_device: str = "cpu"
    embed_batch_size: int = 32
    embed_dim: int = 1024

    # ?? Reranker ?????????????????????????????????????????????????????????????
    reranker_model: str = "cross-encoder/ms-marco-MiniLM-L-6-v2"
    reranker_top_n: int = 5

    # ?? Retrieval ????????????????????????????????????????????????????????????
    bm25_top_k: int = 20
    vector_top_k: int = 20
    rrf_k: int = 60
    final_top_k: int = 10

    # ?? LLM ??????????????????????????????????????????????????????????????????
    llm_provider: Literal["openai", "ollama", "mock"] = "mock"
    openai_api_key: str = "sk-replace-me"
    openai_model: str = "gpt-4o"
    ollama_base_url: str = "http://localhost:11434"
    ollama_model: str = "llama3"

    # ?? Dataset ??????????????????????????????????????????????????????????????
    corpus_version: str = "v1"

    # Vector store
    vector_store: Literal["faiss", "pgvector"] = "faiss"
    faiss_index_path: str = "data/embeddings/faiss_index"


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """Return a cached singleton of Settings."""
    return Settings()


# Convenience alias used throughout the codebase
settings = get_settings()

